"use client";

import React, { useEffect, useState } from "react";
import { Organization, Receipt } from "@/types";
import { formatCurrency, numberToWordsFrench } from "@/lib/utils";
import { generateQrCodeDataUrl } from "@/lib/qr-generator";
import { useApp } from "@/context/AppContext";
import { useApiQuery } from "@/lib/api-client";
import {
  formatDocumentDate,
  paymentMethodLabel,
  type DocumentLanguage,
} from "@/lib/document-format";
import { X, Printer, Share2, CheckCircle2, ShieldCheck } from "lucide-react";

interface QuittanceModalProps {
  receipt: Receipt | null;
  onClose: () => void;
}

export function QuittanceModal({ receipt, onClose }: QuittanceModalProps) {
  const { refreshTrigger } = useApp();
  const { data: org } = useApiQuery<Organization | null>("organization", "/api/organization", {
    refreshKey: refreshTrigger,
  });
  const [qrCodeUrl, setQrCodeUrl] = useState<string>("");

  useEffect(() => {
    if (receipt) {
      const publicVerifyUrl = `${window.location.origin}/verify/${receipt.verificationHash}`;
      generateQrCodeDataUrl(publicVerifyUrl).then(setQrCodeUrl);
    }
  }, [receipt]);

  if (!receipt) return null;

  const lang: DocumentLanguage = org?.settings?.receiptLanguage === "en" ? "en" : "fr";
  const t = {
    fr: {
      receipt: "Quittance de loyer",
      number: "N°",
      issuedOn: "Émise le",
      landlord: "Bailleur / Gestionnaire",
      tenant: "Locataire titulaire",
      property: "Désignation du bien",
      period: "Période concernée",
      rent: "Loyer de la période",
      charges: "Charges locatives",
      totalDue: "Total exigible pour la période",
      paid: "Montant réglé",
      balance: "Solde restant dû",
      settled: "Quittance soldée",
      designation: "Désignation",
      amount: "Montant",
      declaration: "Je soussigné, gestionnaire du bien susmentionné, déclare avoir reçu de",
      received: "la somme de :",
      method: "Mode de règlement",
      reference: "Référence de transaction",
      verified: "Document vérifiable en ligne",
      scan: "Scannez ce QR code pour certifier l'authenticité de cette quittance sur le registre public LOUTIGUI.",
      verifyWithHash: "Vérifiez cette quittance avec son empreinte sur le registre public LOUTIGUI.",
      fingerprint: "Référence de vérification",
      signature: "Signature du bailleur ou de son représentant",
      generated: "Document généré par LOUTIGUI",
    },
    en: {
      receipt: "Rent receipt",
      number: "No.",
      issuedOn: "Issued on",
      landlord: "Landlord / Manager",
      tenant: "Named tenant",
      property: "Leased property",
      period: "Period covered",
      rent: "Rent for the period",
      charges: "Service charges",
      totalDue: "Total due for the period",
      paid: "Amount received",
      balance: "Remaining balance",
      settled: "Fully settled",
      designation: "Description",
      amount: "Amount",
      declaration: "I, the manager of the above-mentioned property, acknowledge having received from",
      received: "the following amount:",
      method: "Payment method",
      reference: "Transaction reference",
      verified: "Online verifiable document",
      scan: "Scan this QR code to verify this receipt on the LOUTIGUI public registry.",
      verifyWithHash: "Verify this receipt with its fingerprint on the LOUTIGUI public registry.",
      fingerprint: "Verification reference",
      signature: "Signature of the landlord or authorised representative",
      generated: "Document generated by LOUTIGUI",
    },
  }[lang];

  const currency = org?.defaultCurrency ?? "XOF";
  const money = (amount: number) => formatCurrency(amount, currency);
  const amountInWords =
    lang === "fr" && currency === "XOF"
      ? ` — ${numberToWordsFrench(Math.round(receipt.amountPaid))}`
      : "";
  const showQrCode = org?.settings?.showQrCode ?? true;
  const legalFooter = org?.settings?.receiptFooter?.trim();
  const verifyUrl = `${window.location.origin}/verify/${receipt.verificationHash}`;
  const settled = receipt.remainingDue <= 0;
  const dueForPeriod = receipt.rentAmount + receipt.chargesAmount;

  const handleWhatsAppShare = () => {
    const text = encodeURIComponent(
      lang === "fr"
        ? `Bonjour ${receipt.tenantName},\n\nVoici votre quittance de loyer LOUTIGUI n° ${receipt.receiptNumber} pour la période de ${receipt.periodLabel}.\n\nMontant réglé : ${money(receipt.amountPaid)}\nBien : ${receipt.unitNumber} (${receipt.buildingName})\n\nVous pouvez vérifier ce document ici : ${verifyUrl}\n\nMerci de votre confiance !`
        : `Hello ${receipt.tenantName},\n\nHere is your LOUTIGUI rent receipt no. ${receipt.receiptNumber} for ${receipt.periodLabel}.\n\nAmount received: ${money(receipt.amountPaid)}\nProperty: ${receipt.unitNumber} (${receipt.buildingName})\n\nYou can verify this document here: ${verifyUrl}\n\nThank you for your trust!`
    );
    window.open(
      `https://wa.me/${receipt.tenantPhone.replace(/[^0-9]/g, "")}?text=${text}`,
      "_blank"
    );
  };

  return (
    <div className="document-overlay fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-slate-950/70 p-3 backdrop-blur-sm sm:p-6">
      <div className="document-modal-shell relative my-4 w-full max-w-4xl overflow-hidden rounded-2xl border border-slate-200 bg-white shadow-2xl">
        {/* Actions – exclues de l'impression */}
        <div className="no-print flex flex-wrap items-center justify-between gap-3 border-b border-slate-800 bg-slate-900 px-5 py-3.5 text-white">
          <div className="flex items-center gap-2">
            <ShieldCheck className="h-5 w-5 text-emerald-400" />
            <div>
              <p className="text-sm font-bold">Aperçu de la quittance de paiement</p>
              <p className="text-[11px] text-slate-400">Document prêt à imprimer ou enregistrer en PDF</p>
            </div>
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={handleWhatsAppShare}
              title="Transmettre directement au locataire sur WhatsApp"
              className="flex items-center gap-1.5 rounded-lg bg-emerald-600 px-3 py-1.5 text-xs font-bold text-white shadow-sm transition hover:bg-emerald-500"
            >
              <Share2 className="h-3.5 w-3.5" />
              WhatsApp
            </button>
            <button
              onClick={() => window.print()}
              className="flex items-center gap-1.5 rounded-lg bg-slate-700 px-3 py-1.5 text-xs font-bold text-white transition hover:bg-slate-600"
            >
              <Printer className="h-3.5 w-3.5" />
              Imprimer / PDF
            </button>
            <button
              onClick={onClose}
              aria-label="Fermer l'aperçu"
              className="rounded-lg p-1.5 text-slate-400 transition hover:bg-slate-800 hover:text-white"
            >
              <X className="h-5 w-5" />
            </button>
          </div>
        </div>

        {/* Document officiel – A4 */}
        <article className="document-print mx-auto min-h-[297mm] w-full max-w-[210mm] bg-white px-8 py-10 font-sans text-[12px] leading-relaxed text-slate-800 sm:px-14 sm:py-14">
          {/* En-tête */}
          <header className="avoid-break flex items-start justify-between gap-6 border-b-2 border-emerald-800 pb-5">
            <div className="min-w-0">
              {org?.logoUrl ? (
                // eslint-disable-next-line @next/next/no-img-element
                <img
                  src={org.logoUrl}
                  alt={`Logo ${org.name}`}
                  className="mb-2 h-12 w-12 rounded-lg border border-slate-200 object-contain"
                />
              ) : (
                <div className="mb-2 flex h-10 w-10 items-center justify-center rounded-lg bg-emerald-800 text-sm font-black text-white">
                  LT
                </div>
              )}
              <p className="truncate text-[13px] font-extrabold uppercase tracking-wide text-slate-900">
                {receipt.organizationName}
              </p>
              <p className="text-[10px] leading-snug text-slate-500">{receipt.organizationAddress}</p>
              <p className="text-[10px] text-slate-500">Tél. {receipt.organizationPhone}</p>
              {org?.email ? <p className="text-[10px] text-slate-500">{org.email}</p> : null}
            </div>
            <div className="shrink-0 text-right">
              <p className="text-[15px] font-black uppercase tracking-wide text-emerald-900">
                {t.receipt}
              </p>
              <p className="mt-1 font-mono text-[11px] font-bold text-slate-700">
                {t.number} {receipt.receiptNumber}
              </p>
              <p className="text-[10px] text-slate-500">
                {t.issuedOn} : {formatDocumentDate(receipt.issuedAt, lang)}
              </p>
            </div>
          </header>

          {/* Parties */}
          <section className="avoid-break mt-6 grid gap-4 sm:grid-cols-2">
            <div className="rounded-lg border border-slate-200 bg-slate-50 p-4">
              <p className="mb-1.5 text-[10px] font-bold uppercase tracking-wider text-emerald-800">
                {t.landlord}
              </p>
              <p className="text-[12px] font-bold text-slate-900">{receipt.organizationName}</p>
              <p className="text-[11px] text-slate-600">
                {org?.managementType === "AGENCY"
                  ? lang === "fr"
                    ? "Agence gestionnaire mandatée"
                    : "Authorised managing agency"
                  : lang === "fr"
                    ? "Propriétaire ou représentant mandaté"
                    : "Owner or authorised representative"}
              </p>
            </div>
            <div className="rounded-lg border border-slate-200 bg-slate-50 p-4">
              <p className="mb-1.5 text-[10px] font-bold uppercase tracking-wider text-emerald-800">
                {t.tenant}
              </p>
              <p className="text-[12px] font-bold text-slate-900">{receipt.tenantName}</p>
              <p className="text-[11px] text-slate-600">Tél. {receipt.tenantPhone}</p>
            </div>
          </section>

          {/* Bien et période */}
          <section className="avoid-break mt-5 grid gap-4 border-y border-slate-200 py-4 sm:grid-cols-2">
            <div>
              <p className="mb-1 text-[10px] font-bold uppercase tracking-wider text-slate-500">
                {t.property}
              </p>
              <p className="text-[12px] font-bold text-slate-900">{receipt.unitNumber}</p>
              <p className="text-[11px] text-slate-600">{receipt.buildingName}</p>
            </div>
            <div>
              <p className="mb-1 text-[10px] font-bold uppercase tracking-wider text-slate-500">
                {t.period}
              </p>
              <p className="text-[12px] font-bold text-slate-900">{receipt.periodLabel}</p>
            </div>
          </section>

          {/* Détail financier */}
          <section className="avoid-break mt-5">
            <table className="w-full border-collapse text-[11px]">
              <thead>
                <tr className="border-b-2 border-slate-800 text-[10px] uppercase tracking-wider text-slate-600">
                  <th className="pb-2 text-left font-bold">{t.designation}</th>
                  <th className="pb-2 text-right font-bold">{t.amount}</th>
                </tr>
              </thead>
              <tbody>
                <tr className="border-b border-slate-200">
                  <td className="py-2 text-slate-700">{t.rent}</td>
                  <td className="py-2 text-right font-semibold">{money(receipt.rentAmount)}</td>
                </tr>
                <tr className="border-b border-slate-200">
                  <td className="py-2 text-slate-700">{t.charges}</td>
                  <td className="py-2 text-right font-semibold">{money(receipt.chargesAmount)}</td>
                </tr>
                <tr className="border-b border-slate-300 font-bold">
                  <td className="py-2 text-slate-800">{t.totalDue}</td>
                  <td className="py-2 text-right text-slate-900">{money(dueForPeriod)}</td>
                </tr>
                <tr className="bg-emerald-50 font-bold text-emerald-950">
                  <td className="py-2.5 pl-2">{t.paid}</td>
                  <td className="py-2.5 pr-2 text-right text-emerald-800">
                    {money(receipt.amountPaid)}
                  </td>
                </tr>
                <tr className="border-b border-slate-200">
                  <td className="py-2 pl-2 text-slate-600">{t.balance}</td>
                  <td className="py-2 pr-2 text-right font-semibold text-slate-700">
                    {settled ? t.settled : money(receipt.remainingDue)}
                  </td>
                </tr>
              </tbody>
            </table>
          </section>

          {/* Déclaration de règlement */}
          <section className="avoid-break mt-5 rounded-lg border border-slate-200 bg-slate-50 p-4">
            <p className="text-[11px] text-slate-700">
              {t.declaration} <strong>{receipt.tenantName}</strong> {t.received}
            </p>
            <p className="mt-1 text-[13px] font-extrabold uppercase text-emerald-900">
              {money(receipt.amountPaid)}
              {amountInWords}
            </p>
            <p className="mt-2 text-[10px] text-slate-600">
              {t.method} : <strong>{paymentMethodLabel(receipt.paymentMethod, receipt.provider, lang)}</strong>
              {receipt.transactionRef ? (
                <>
                  {" · "}
                  {t.reference} : <span className="font-mono">{receipt.transactionRef}</span>
                </>
              ) : null}
            </p>
          </section>

          {/* Vérification et signature */}
          <section className="avoid-break mt-6 flex flex-wrap items-start justify-between gap-6 border-t border-slate-200 pt-4">
            <div className="flex items-start gap-3">
              {showQrCode && qrCodeUrl ? (
                // eslint-disable-next-line @next/next/no-img-element
                <img
                  src={qrCodeUrl}
                  alt="QR Code de vérification"
                  className="h-20 w-20 rounded border border-slate-300 bg-white p-0.5"
                />
              ) : null}
              <div className="max-w-[260px]">
                <p className="flex items-center gap-1 text-[11px] font-bold text-emerald-800">
                  <CheckCircle2 className="h-3.5 w-3.5" />
                  {t.verified}
                </p>
                <p className="mt-1 text-[10px] leading-snug text-slate-500">
                  {showQrCode ? t.scan : t.verifyWithHash}
                </p>
                <p className="mt-1 break-all font-mono text-[9px] text-slate-500">{verifyUrl}</p>
                <p className="mt-1 text-[9px] font-bold uppercase tracking-wider text-slate-400">
                  {t.fingerprint}
                </p>
                <p className="break-all font-mono text-[9px] text-slate-500">
                  {receipt.verificationHash}
                </p>
              </div>
            </div>
            <div className="min-w-[200px] text-right">
              <p className="text-[10px] font-bold uppercase tracking-wide text-slate-700">
                {t.signature}
              </p>
              <div className="mt-10 border-t border-slate-500 pt-1.5 text-[10px] text-slate-500">
                {receipt.organizationName}
              </div>
            </div>
          </section>

          {legalFooter ? (
            <p className="avoid-break mt-4 border-t border-slate-200 pt-3 text-[10px] italic leading-snug text-slate-500">
              {legalFooter}
            </p>
          ) : null}

          <footer className="avoid-break mt-6 flex items-center justify-between border-t border-slate-200 pt-3 text-[9px] uppercase tracking-wider text-slate-400">
            <span>{t.generated}</span>
            <span className="font-mono normal-case tracking-normal">{receipt.receiptNumber}</span>
          </footer>
        </article>
      </div>
    </div>
  );
}
